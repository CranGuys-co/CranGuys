// Copies the game code the cg-api Edge Function runs (the progress rules and everything they import) into
// supabase/functions/cg-api/game/, keeping the same folders so the imports still work.
//   npm run build:functions
// tests/cloudApi.test.js fails if the copies are out of date, so run this after changing any of them.
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = 'supabase/functions/cg-api/game';
const ENTRIES = ['online/progress.js', 'online/records.js'];

// every file under src/ the entries import, directly or not (paths relative to src/)
export function closure() {
  const seen = new Set();
  const visit = (rel) => {
    if (seen.has(rel)) return;
    seen.add(rel);
    for (const m of readFileSync(join(ROOT, 'src', rel), 'utf8').matchAll(/^import .* from '([^']+)';$/gm)) visit(posix.join(posix.dirname(rel), m[1]));
  };
  ENTRIES.forEach(visit);
  return [...seen].sort();
}
export const copied = (rel) => `// GENERATED by \`npm run build:functions\` from src/${rel}. Do not edit: change the original.\n${readFileSync(join(ROOT, 'src', rel), 'utf8')}`;
export const outPath = (rel) => join(ROOT, OUT, rel);

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  rmSync(join(ROOT, OUT), { recursive: true, force: true });
  for (const rel of closure()) {
    mkdirSync(dirname(outPath(rel)), { recursive: true });
    writeFileSync(outPath(rel), copied(rel));
    console.log(`Wrote ${OUT}/${rel}`);
  }
}
