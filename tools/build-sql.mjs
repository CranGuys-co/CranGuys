// Joins every file in supabase/migrations/ (in order) into supabase/setup.sql, the one file you paste into the
// Supabase SQL Editor (see SUPABASE_SETUP.md).
//   npm run build:sql
// tests/cloudApi.test.js fails if setup.sql is out of date.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'supabase/migrations');

export function setupSql() {
  const files = readdirSync(DIR).filter((f) => f.endsWith('.sql')).sort();
  const head = `-- CranGuys: everything the database needs, in one file. GENERATED by \`npm run build:sql\` from
-- supabase/migrations/ — edit those, not this. Paste it all into Supabase → SQL Editor → New query → Run.
-- Safe to run again (for example after an update adds a new migration).
`;
  return head + files.map((f) => `\n-- ======================================================== ${f}\n\n${readFileSync(join(DIR, f), 'utf8').trim()}\n`).join('');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(ROOT, 'supabase/setup.sql'), setupSql());
  console.log('Wrote supabase/setup.sql');
}
